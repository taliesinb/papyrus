"""Download and build src/papyrus/data/words.txt: common English words (pagetext.words).

    uv run python tools/words/fetch.py [OUT_DIR]      # default: src/papyrus/data

The installers (apps/macos/build.py, apps/linux/install.py) run it when words.txt is missing.
The file is generated, not committed (.gitignore). Without it papyrus works, but leaves words that
small caps split ('G ATED D ELTA') as they are.

Source: `American/2of12.txt` from Alan Beale's 12dicts 6.0.2 (https://wordlist.aspell.net/12dicts/):
the words found in at least 2 of 12 mostly learner's and desk dictionaries, so obscure entries
('amba', 'ule', 'odel') are left out. Public domain ("I explicitly release them to the public
domain, but request acknowledgment of their use"): thanks to Alan Beale. It has no inflected forms
('network', not 'networks'); pagetext.is_word handles endings. 2of12inf, the variant with them, is
not used: its inflections come from AGID, which carries notices of its own.

The zip and the file inside it are checked against their sha256, so a changed upstream fails
loudly instead of shipping a different list. The download goes through papyrus's HttpClient, so
it is recorded in the web services store (AGENTS.md, invariant 9) like every other request.
"""

from __future__ import annotations

import hashlib
import io
import re
import sys
import tempfile
import zipfile
from pathlib import Path

from papyrus import http

REPO = Path(__file__).resolve().parents[2]
URL = "https://downloads.sourceforge.net/wordlist/12dicts-6.0.2.zip"
ZIP_SHA256 = "64ac1d35acb66b550c7ebc56e080b62e0bad8f5984d72059dc2e05ac48780e52"
MEMBER = "American/2of12.txt"
MEMBER_SHA256 = "235f1d8bb6155ffae3797b514e55916ae8905acb77ec08bb643cf0440e84ff1a"
WORD = re.compile(r"[A-Za-z][A-Za-z'\-]*")  # drops "'tis" and phrases

README = """\
# words.txt

Generated by tools/words/fetch.py (don't edit): {n:,} common English words, one per line,
lowercase, from `{member}` of Alan Beale's 12dicts 6.0.2 ({url}; zip sha256 {zip_sha}, file sha256
{member_sha}), deduplicated, {dropped} entries that start with an apostrophe or hold anything but
letters, apostrophes and hyphens dropped. Public domain; thanks to Alan Beale for 12dicts.
"""


def sha256(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def fetch(out_dir: Path) -> Path:
    with tempfile.TemporaryDirectory() as tmp:
        dest = Path(tmp) / "12dicts.zip"
        http.default_client().download(URL, dest, max_bytes=20 << 20)
        data = dest.read_bytes()
    if sha256(data) != ZIP_SHA256:
        raise SystemExit(f"{URL}: sha256 {sha256(data)}, expected {ZIP_SHA256}")
    raw = zipfile.ZipFile(io.BytesIO(data)).read(MEMBER)
    if sha256(raw) != MEMBER_SHA256:
        raise SystemExit(f"{MEMBER}: sha256 {sha256(raw)}, expected {MEMBER_SHA256}")
    entries = [w for w in raw.decode("latin-1").replace("\r", "").split("\n") if w]
    words = sorted({w.lower() for w in entries if WORD.fullmatch(w)})
    dropped = sum(1 for w in entries if not WORD.fullmatch(w))
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / "words.txt"
    tmp_out = out.with_suffix(".tmp")
    tmp_out.write_text("\n".join(words) + "\n", encoding="utf-8", newline="\n")
    tmp_out.replace(out)  # never a half-written list
    (out_dir / "words.README.md").write_text(
        README.format(n=len(words), member=MEMBER, url=URL, zip_sha=ZIP_SHA256, member_sha=MEMBER_SHA256,
                      dropped=dropped), encoding="utf-8")
    print(f"wrote {out}: {len(words)} words", file=sys.stderr)
    return out


if __name__ == "__main__":
    fetch(Path(sys.argv[1]) if len(sys.argv) > 1 else REPO / "src" / "papyrus" / "data")
